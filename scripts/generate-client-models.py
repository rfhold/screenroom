#!/usr/bin/env python3
"""Generate plain domain records, independently of prost's wire representation."""
import re
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true", help="fail on generated model drift without writing")
args = parser.parse_args()
messages = []
enums = []
names = {}
for package in ("catalog", "common", "user", "playback_gateway"):
    path = root / f"proto/screenroom/{package}/v1/{package}.proto"
    proto = path.read_text()
    namespace = re.search(r"\bpackage\s+([\w.]+);", proto).group(1)
    for name, body in re.findall(r"enum (\w+)\s*\{([^}]*)\}", proto):
        if name in names:
            raise ValueError(f"Domain name collision: {names[name]} and {namespace}.{name}")
        names[name] = f"{namespace}.{name}"
        prefix = re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper() + "_"
        variants = []
        for variant in re.findall(r"\b(\w+)\s*=\s*\d+;", body):
            if not variant.startswith(prefix):
                raise ValueError(f"Enum value {variant} must start with {prefix}")
            value = variant[len(prefix):].lower()
            variants.append(("".join(part.title() for part in value.split("_")), value))
        enums.append((namespace, name, variants))
    for name, body in re.findall(r"message (\w+)\s*\{([^}]*)\}", proto):
        if package == "user" and name == "Page":
            continue  # Public pagination has the same domain shape as catalog.Page.
        if name in names:
            raise ValueError(f"Domain name collision: {names[name]} and {namespace}.{name}")
        names[name] = f"{namespace}.{name}"
        messages.append((namespace, name, body))
domain_types = {
    qualified: "MediaLibrary" if name == "Library" else name
    for name, qualified in names.items()
    if not name.endswith(("Request", "Response")) or name == "SearchRequest"
    or qualified.startswith("screenroom.playback_gateway.v1.")
}
domain_types["screenroom.user.v1.Page"] = "Page"
enum_types = {f"{namespace}.{name}" for namespace, name, _ in enums}
types = {"string": "String", "bool": "bool", "uint32": "u32", "uint64": "u64", "double": "f64"}
out = ["// Generated by scripts/generate-client-models.py; no prost types cross this boundary.", "use serde::{Deserialize, Serialize};", ""]
for namespace, name, variants in enums:
    out += ["#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]", '#[cfg_attr(not(target_arch = "wasm32"), derive(uniffi::Enum))]', f"pub enum {name} {{"]
    for index, (variant, value) in enumerate(variants):
        if index == 0:
            out.append("    #[default]")
        out += [f'    #[serde(rename = "{value}")]', f"    {variant},"]
    out += ["}", ""]
for namespace, name, body in messages:
    if name.endswith(("Request", "Response")) and name != "SearchRequest" and namespace != "screenroom.playback_gateway.v1":
        continue
    out += ["#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]", '#[cfg_attr(not(target_arch = "wasm32"), derive(uniffi::Record))]', f"pub struct {domain_types[f'{namespace}.{name}']} {{"]
    for mode, kind, field in re.findall(r"\b(?:(optional|repeated)\s+)?([\w.]+)\s+(\w+)\s*=\s*\d+;", body):
        if kind in types:
            native = types[kind]
            is_message = False
        else:
            qualified = kind.lstrip(".") if "." in kind else f"{namespace}.{kind}"
            if qualified not in domain_types:
                raise ValueError(f"No domain type for {qualified} in {namespace}.{name}.{field}")
            native = domain_types[qualified]
            is_message = qualified not in enum_types
        if mode == "repeated":
            native = f"Vec<{native}>"
        elif mode == "optional" or is_message:
            native = f"Option<{native}>"
        out.append(f"    pub {field}: {native},")
    out += ["}", ""]
for name, fields in {
    "ItemPage": {"items": "Vec<Item>", "next_page_token": "String"},
    "JellyfinSourcePage": {"sources": "Vec<JellyfinSource>", "next_page_token": "String"},
    "JellyfinProfilePage": {"profiles": "Vec<JellyfinProfile>", "next_page_token": "String"},
    "CreditPage": {"credits": "Vec<Credit>", "next_page_token": "String"},
    "SearchCapabilities": {"methods": "Vec<String>", "types": "Vec<String>", "sources": "Vec<String>", "semantic_description": "String", "maximum_query_length": "u32"},
    "LibraryPage": {"libraries": "Vec<MediaLibrary>", "next_page_token": "String"},
    "ArtworkPage": {"artwork": "Vec<Artwork>", "next_page_token": "String"},
    "SearchPage": {"items": "Vec<Item>", "next_page_token": "String", "effective_methods": "Option<SearchMethods>", "degradation_reason": "String"},
    "ClientConfig": {"endpoint": "String", "user_id": "String", "timeout_ms": "u32"},
    "ClientSettings": {"scope": "Option<SourceLibraryScope>", "source": "String", "types": "Option<SearchTypes>", "methods": "Option<SearchMethods>"},
}.items():
    out += ["#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]", '#[cfg_attr(not(target_arch = "wasm32"), derive(uniffi::Record))]', f"pub struct {name} {{"]
    for field, kind in fields.items():
        if name == "ClientConfig" and field == "user_id":
            out.append("    /// Empty for anonymous catalog reads, otherwise an explicit trusted-local UUID; not authentication.")
        out.append(f"    pub {field}: {kind},")
    out += ["}", ""]
rust = "\n".join(out)
rust_path = root / "crates/screenroom-client-core/src/models.rs"
ts = ["// Generated domain records; field names match Rust and the gRPC contracts."]
for namespace, name, variants in enums:
    ts.append(f"export type {name} = " + " | ".join(f'"{value}"' for _, value in variants) + ";")
def ts_type(kind):
    if kind.startswith("Option<"):
        return ts_type(kind[7:-1]) + " | null"
    if kind.startswith("Vec<"):
        return "Array<" + ts_type(kind[4:-1]) + ">"
    return {"String": "string", "bool": "boolean", "u32": "number", "u64": "number", "f64": "number"}.get(kind, kind)
for name, body in re.findall(r"pub struct (\w+) \{([^}]+)\}", rust):
    ts.append(f"export interface {name} {{")
    for field, kind in re.findall(r"pub (\w+): (.+),", body):
        ts.append(f"  {field}: {ts_type(kind)};")
    ts.append("}")
for path, content in [(rust_path, rust), (root / "crates/screenroom-client-core/src/wasm-models.ts", "\n".join(ts) + "\n")]:
    if args.check:
        if path.read_text() != content:
            raise SystemExit(f"Generated client model drift: {path.relative_to(root)}")
    else:
        path.write_text(content)
